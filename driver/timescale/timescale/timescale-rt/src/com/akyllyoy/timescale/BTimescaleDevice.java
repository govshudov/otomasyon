  /**
   * Kaynaklari verilen yapilandirmayla kurar.
   * Yapilandirma cagirandan gelir cunku sifre yalnizca Engine thread'inde okunabilir.
   */
  private void openResources(TsConfig cfg)
  {
    activeConfig = cfg;

    synchronized (controlLock)
    {
      if (control == null)
      {
        control = new TsConnection(cfg, getName() + "-ctl");
      }
      if (registry == null)
      {
        registry = new TsPointRegistry(cfg.schema);
      }
    }

    if (queue == null)
    {
      queue = new TsWriteQueue(
        cfg,
        cfg.schema,
        getQueueCapacity(),
        getBatchSize(),
        getFlushInterval().getMillis(),
        TsWriteQueue.OverflowPolicy.DROP_OLDEST,
        getUpdateLiveTable(),
        getName());
      queue.start();
    }

    if (getAutoCreateSchema())
    {
      try
      {
        synchronized (controlLock)
        {
          TsSchema.ensureSchema(control, cfg.schema);
        }
      }
      catch (Exception e)
      {
        LOG.log(Level.WARNING, "autoCreateSchema basarisiz", e);
        setLastWriteError(shortMessage(e));
      }
    }
  }

  private void closeResources()
  {
    TsWriteQueue q = queue;
    queue = null;
    if (q != null) { q.stop(); }

    synchronized (controlLock)
    {
      if (control != null) { control.closeQuietly(); control = null; }
      if (registry != null) { registry.invalidate(); registry = null; }
    }
  }

