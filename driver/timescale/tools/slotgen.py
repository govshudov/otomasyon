#!/usr/bin/env python3
"""
Slot-o-Matic yerine gecen kod ureticisi.

Niagara'nin kendi Slot-o-Matic'i Gradle eklentisiyle gelir; bu projede
Gradle kullanmadigimiz icin @NiagaraProperty / @NiagaraAction
aciklamalarindan uretilen "BAJA AUTO GENERATED CODE" bolgesini burada
uretiyoruz.

Kullanim:
    python3 tools/slotgen.py <Sinif.java> [...]

Dosyada zaten bir uretilmis bolge varsa DEGISTIRILIR, yoksa sinif
govdesinin basina EKLENIR. Elle yazilmis kod korunur.
"""

import re
import sys

# Baja ilkel tipleri: (getter, setter) ciftleri
PRIMITIVES = {
    "String":  ("getString", "setString"),
    "int":     ("getInt", "setInt"),
    "long":    ("getLong", "setLong"),
    "boolean": ("getBoolean", "setBoolean"),
    "double":  ("getDouble", "setDouble"),
    "float":   ("getFloat", "setFloat"),
}

BEGIN = "//region /*+ ------------ BEGIN BAJA AUTO GENERATED CODE ------------ +*/"
END = "//endregion /*+ ------------ END BAJA AUTO GENERATED CODE -------------- +*/"


def cap(s):
    return s[0].upper() + s[1:]


def parse_annotations(src, name):
    """@NiagaraProperty(...) / @NiagaraAction(...) bloklarini sirasiyla ayikla."""
    out = []
    i = 0
    tag = "@Niagara" + name + "("
    while True:
        i = src.find(tag, i)
        if i < 0:
            break
        # parantez dengesini takip ederek blogu kapat
        j = i + len(tag)
        depth = 1
        while j < len(src) and depth > 0:
            c = src[j]
            if c == '"':                      # dize icindeki parantezleri atla
                j += 1
                while j < len(src) and src[j] != '"':
                    if src[j] == '\\':
                        j += 1
                    j += 1
            elif c == '(':
                depth += 1
            elif c == ')':
                depth -= 1
            j += 1
        out.append(src[i + len(tag):j - 1])
        i = j
    return out


def field(block, key):
    """block icinden `key = <deger>` ayikla (dize veya ifade)."""
    m = re.search(r'\b' + key + r'\s*=\s*"((?:[^"\\]|\\.)*)"', block)
    if m:
        return ('str', m.group(1))
    m = re.search(r'\b' + key + r'\s*=\s*([^,\n][^,\n]*)', block)
    if m:
        return ('expr', m.group(1).strip())
    return None


def unescape(s):
    return s.replace('\\"', '"').replace('\\\\', '\\')


def gen_property(block):
    name = unescape(field(block, "name")[1])
    typ = unescape(field(block, "type")[1])

    dv = field(block, "defaultValue")
    # defaultValue her zaman String literal olarak yazilir; icerigi JAVA IFADESIDIR
    default = unescape(dv[1]) if dv else None
    if default is None:
        raise SystemExit("defaultValue eksik: " + name)

    fl = field(block, "flags")
    flags = fl[1] if fl else "0"

    lines = []
    lines.append('  //region Property "%s"' % name)
    lines.append('')
    lines.append('  public static final Property %s = newProperty(%s, %s, null);'
                 % (name, flags, default))
    if typ in PRIMITIVES:
        g, s = PRIMITIVES[typ]
        lines.append('  public %s get%s() { return %s(%s); }' % (typ, cap(name), g, name))
        lines.append('  public void set%s(%s v) { %s(%s, v, null); }'
                     % (cap(name), typ, s, name))
    else:
        lines.append('  public %s get%s() { return (%s)get(%s); }'
                     % (typ, cap(name), typ, name))
        lines.append('  public void set%s(%s v) { set(%s, v, null); }'
                     % (cap(name), typ, name))
    lines.append('  //endregion Property "%s"' % name)
    lines.append('')
    return lines


def gen_action(block):
    name = unescape(field(block, "name")[1])
    fl = field(block, "flags")
    flags = fl[1] if fl else "0"

    return [
        '  //region Action "%s"' % name,
        '',
        '  public static final Action %s = newAction(%s, null);' % (name, flags),
        '  public void %s() { invoke(%s, null, null); }' % (name, name),
        '',
        '  //endregion Action "%s"' % name,
        '',
    ]


def generate(path):
    src = open(path, encoding='utf-8').read()

    m = re.search(r'public\s+(?:abstract\s+)?class\s+(B\w+)', src)
    if not m:
        raise SystemExit("sinif adi bulunamadi: " + path)
    cls = m.group(1)
    pkg = re.search(r'package\s+([\w.]+)\s*;', src).group(1)

    # uretilmis bolge varsa aciklamalari ondan ONCEKI metinden oku
    head = src.split(BEGIN)[0] if BEGIN in src else src

    body = []
    body.append(BEGIN)
    body.append("//@formatter:off")
    body.append("/*@ $%s.%s(2979906276)1.0$ @*/" % (pkg, cls))
    body.append("/* Generated by slotgen.py - Slot-o-Matic yerine */")
    body.append("")

    for b in parse_annotations(head, "Property"):
        body.extend(gen_property(b))
    for b in parse_annotations(head, "Action"):
        body.extend(gen_action(b))

    body.append('  //region Type')
    body.append('')
    body.append('  @Override')
    body.append('  public Type getType() { return TYPE; }')
    body.append('  public static final Type TYPE = Sys.loadType(%s.class);' % cls)
    body.append('')
    body.append('  //endregion Type')
    body.append("//@formatter:on")
    body.append(END)

    region = "\n".join(body)

    if BEGIN in src:
        start = src.index(BEGIN)
        stop = src.index(END) + len(END)
        out = src[:start] + region + src[stop:]
    else:
        # sinif govdesinin acilis suslu parantezinden hemen sonra ekle
        brace = src.index('{', src.index('class ' + cls))
        out = src[:brace + 1] + "\n" + region + "\n" + src[brace + 1:]

    open(path, 'w', encoding='utf-8').write(out)
    nprop = len(parse_annotations(head, "Property"))
    nact = len(parse_annotations(head, "Action"))
    print("%s: %d property, %d action" % (cls, nprop, nact))


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    for p in sys.argv[1:]:
        generate(p)
